// 生成 THIRD_PARTY.txt —— 遍历 node_modules，提取每个包的
// name / license / author / repository，汇总成集中版权清单。
// 满足 MIT/Apache 的"保留版权声明"义务的集中展示需求。
// 运行：node scripts/gen-licenses.js
// 安装包内 node_modules/<pkg>/LICENSE 仍随包分发（asar: false），本文件是集中索引。

const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..', 'node_modules')
const out = path.join(__dirname, '..', 'licenses', 'THIRD_PARTY.txt')

function readPkg(dir) {
  const p = path.join(dir, 'package.json')
  if (!fs.existsSync(p)) return null
  try { return JSON.parse(fs.readFileSync(p, 'utf8')) } catch { return null }
}

function fmtAuthor(a) {
  if (!a) return ''
  if (typeof a === 'string') return a
  const n = a.name || ''
  const e = a.email ? ` <${a.email}>` : ''
  const u = a.url ? ` (${a.url})` : ''
  return `${n}${e}${u}`
}

function fmtRepo(r) {
  if (!r) return ''
  if (typeof r === 'string') return r
  return r.url || ''
}

function cleanRepo(url) {
  if (!url) return ''
  let u = url
  u = u.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/^git@([^:]+):/, 'https://$1/')
  u = u.replace(/\.git$/, '')
  return u
}

const pkgs = []
function walk(dir, depth) {
  if (depth > 4) return
  let entries
  try { entries = fs.readdirSync(dir, { withFileTypes: true }) } catch { return }
  for (const e of entries) {
    if (!e.isDirectory()) continue
    if (e.name.startsWith('.')) continue
    const sub = path.join(dir, e.name)
    // scoped: @scope/pkg
    if (e.name.startsWith('@')) {
      let subs
      try { subs = fs.readdirSync(sub, { withFileTypes: true }) } catch { continue }
      for (const s of subs) {
        if (!s.isDirectory()) continue
        const pkgDir = path.join(sub, s.name)
        const pkg = readPkg(pkgDir)
        if (pkg && pkg.name) pkgs.push({ pkg, dir: pkgDir })
      }
      continue
    }
    const pkg = readPkg(sub)
    if (pkg && pkg.name) pkgs.push({ pkg, dir: sub })
  }
}

walk(root, 0)

// 去重（按 name@version）
const seen = new Set()
const uniq = []
for (const p of pkgs) {
  const k = `${p.pkg.name}@${p.pkg.version}`
  if (seen.has(k)) continue
  seen.add(k)
  uniq.push(p)
}
uniq.sort((a, b) => a.pkg.name.localeCompare(b.pkg.name))

const lines = []
lines.push('========================================================================')
lines.push('  PicRand — Complete Third-Party Package List')
lines.push('  Generated by scripts/gen-licenses.js')
lines.push('  Each package\'s LICENSE file is also distributed in the installer')
lines.push('  under node_modules/<package>/LICENSE.')
lines.push('========================================================================')
lines.push('')
lines.push(`Total packages: ${uniq.length}`)
lines.push('')

for (const { pkg } of uniq) {
  const lic = Array.isArray(pkg.licenses) ? pkg.licenses.map(l => l.type || l.name || 'UNKNOWN').join(', ')
    : (pkg.license && typeof pkg.license === 'string') ? pkg.license
    : (pkg.license && pkg.license.type) ? pkg.license.type
    : 'UNKNOWN'
  const author = fmtAuthor(pkg.author) || fmtAuthor(pkg.maintainers && pkg.maintainers[0]) || ''
  const repo = cleanRepo(fmtRepo(pkg.repository)) || cleanRepo(pkg.homepage || '') || ''
  lines.push(`  ${pkg.name}@${pkg.version}    [${lic}]`)
  if (author) lines.push(`    author: ${author}`)
  if (repo) lines.push(`    source: ${repo}`)
  lines.push('')
}

lines.push('========================================================================')
lines.push('  License full texts:')
lines.push('    MIT:        https://opensource.org/licenses/MIT')
lines.push('    Apache-2.0: https://www.apache.org/licenses/LICENSE-2.0')
lines.push('    BSD:        https://opensource.org/licenses/BSD-3-Clause')
lines.push('    ISC:        https://opensource.org/licenses/ISC')
lines.push('    LGPL-2.1:   https://www.gnu.org/licenses/old-licenses/lgpl-2.1.txt')
lines.push('========================================================================')

fs.writeFileSync(out, lines.join('\n'), 'utf8')
console.log(`Wrote ${out} (${uniq.length} packages)`)
